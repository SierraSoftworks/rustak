    #[tokio::test]
    async fn an_hs256_or_unsigned_token_is_refused() {
        let (_db, _secrets, jwt) = issuer().await;
        let (token, claims) = jwt.issue(&user(), "admin", None, None).unwrap();
        let payload = token.split('.').nth(1).unwrap();

        // The two classic forgeries: swap the algorithm to `none`, or to an
        // HMAC keyed on the public key we publish.
        for header in [
            r#"{"alg":"none","typ":"JWT"}"#,
            r#"{"alg":"HS256","typ":"JWT"}"#,
        ] {
            let forged = format!("{}.{payload}.", B64.encode(header));

            assert!(jwt.verify(&forged).is_err(), "{header}");
        }

        let hs256 = jsonwebtoken::encode(
            &jsonwebtoken::Header::new(Algorithm::HS256),
            &claims,
            &EncodingKey::from_secret(b"guess"),
        )
        .unwrap();
        assert!(jwt.verify(&hs256).is_err());
    }

    #[tokio::test]
    async fn a_tampered_payload_is_refused() {
        let (_db, _secrets, jwt) = issuer().await;
        let (token, mut claims) = jwt.issue(&user(), "marti", None, None).unwrap();
        claims.scope = "admin".to_string();

        let mut parts = token.split('.');
        let forged = format!(
            "{}.{}.{}",
            parts.next().unwrap(),
            B64.encode(serde_json::to_vec(&claims).unwrap()),
            parts.nth(1).unwrap()
        );

        assert!(jwt.verify(&forged).is_err());
        assert!(jwt.verify("not-a-token").is_err());
        assert!(jwt.verify("").is_err());
    }

