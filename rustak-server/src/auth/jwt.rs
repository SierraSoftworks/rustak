    #[tokio::test]
    async fn a_token_signed_before_a_rotation_still_verifies() {
        let (db, secrets, mut jwt) = issuer().await;
        let (before, _) = jwt.issue(&user(), "admin", None, None).unwrap();
        let old_kid = jwt.active_kid().to_string();

        jwt.rotate(&db, &secrets).await.unwrap();
        let (after, _) = jwt.issue(&user(), "admin", None, None).unwrap();

        assert_ne!(jwt.active_kid(), old_kid);
        assert!(
            jwt.verify(&before).is_ok(),
            "the retired key still verifies"
        );
        assert!(jwt.verify(&after).is_ok());

        // And a restart picks the rotation up rather than resurrecting the old
        // key as the active one.
        let restarted = JwtIssuer::load_or_create(&db, &secrets, &auth(), "https://unused")
            .await
            .unwrap();
        assert_eq!(restarted.active_kid(), jwt.active_kid());
        assert!(restarted.verify(&before).is_ok());
    }

    #[tokio::test]
    async fn the_published_key_material_is_public_only() {
        let (_db, _secrets, jwt) = issuer().await;

        let token_key = jwt.token_key_json();
        let jwks = jwt.jwks();

        assert_eq!(token_key["alg"], "SHA256withRSA");
        let pem = token_key["value"].as_str().unwrap();
        assert!(pem.starts_with("-----BEGIN PUBLIC KEY-----"), "{pem}");
        assert!(!pem.contains("PRIVATE"), "{pem}");

        let key = &jwks["keys"][0];
        assert_eq!(key["kty"], "RSA");
        assert_eq!(key["alg"], "RS256");
        assert_eq!(key["use"], "sig");
        assert_eq!(key["kid"], jwt.active_kid());
        assert!(key["n"].as_str().unwrap().len() > 300, "a 2048-bit modulus");
        assert!(
            jwks["keys"][1].is_null(),
            "only one key before any rotation"
        );
        assert!(!jwks.to_string().contains('d'.to_string().as_str()) || key["d"].is_null());
    }

    #[tokio::test]
    async fn the_stored_key_is_sealed() {
        let (db, secrets, jwt) = issuer().await;

        let row = db
            .oauth_keys()
            .get(jwt.active_kid())
            .await
            .unwrap()
            .unwrap();

        assert_eq!(row.alg, KeyAlgorithm::Rs256);
        assert_eq!(row.purpose, KeyPurpose::AccessToken);
        assert!(!row.private_sealed.contains("PRIVATE"));
        assert!(row.public_jwk.unwrap().contains("\"kty\":\"RSA\""));
        assert!(!format!("{jwt:?}").contains(&row.private_sealed));

        // A different encryption key cannot open it.
        assert!(
            JwtIssuer::load_or_create(&db, &SecretStore::ephemeral(), &auth(), "https://unused")
                .await
                .is_err()
        );
        let _ = secrets;
    }

