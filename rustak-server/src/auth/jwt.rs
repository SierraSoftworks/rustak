//! The RS256 access tokens rustak issues, and the keys that sign them.
//!
//! One token format serves everything: the admin UI after a sign-in, CloudTAK
//! after `/oauth/token`, and sidecars. That is deliberate — a second format
//! would be a second thing to get subtly wrong — but it means the format is
//! pinned by the least forgiving consumer, and that consumer is CloudTAK.
//!
//! # The shape is a compatibility contract, not a preference
//!
//! node-tak, the library CloudTAK logs in with, does not verify our signature
//! or fetch our keys. It base64-decodes the **whole token string** as one blob
//! (the dots are simply not in the base64 alphabet, so they vanish), splits the
//! result on `}`, and parses the second piece as the claims. Three consequences
//! follow, and all three are asserted by the tests at the bottom of this file:
//!
//! 1. **The header bytes are fixed** at [`JWT_HEADER_JSON`]. It is 27 bytes — a
//!    whole number of three-byte groups — so its base64 is exactly 36
//!    characters and the payload that follows starts on a group boundary. A
//!    header of 26 or 28 bytes shifts every following byte and login fails with
//!    a decode error nobody would think to blame on the header.
//! 2. **Claims are flat scalars.** The payload must contain exactly one `}` —
//!    its own closing brace — so a nested object anywhere would truncate the
//!    claims at the inner brace. [`JwtIssuer::issue`] refuses to mint a token
//!    that breaks this rather than emitting one that fails mysteriously later.
//! 3. **`aud` is a string**, not the array the specification also permits.
//!
//! None of this weakens *our* verification: [`JwtIssuer::verify`] checks the
//! signature, requires RS256, and requires the audience, issuer and expiry.
//!
//! # Keys and rotation
//!
//! The signing key is RSA-2048, generated by the pure-Rust `rsa` crate, sealed
//! with [`SecretContext::JwtSigningKey`] and stored in `oauth_keys`. Retiring a
//! key does not delete it: tokens it signed stay verifiable until they expire,
//! which is what makes a rotation invisible to whoever is already signed in.
//! Tokens carry no `kid` — there is no room in a fixed 27-byte header — so
//! verification tries the active key and then each retired one.

